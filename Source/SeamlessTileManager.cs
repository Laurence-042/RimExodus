using System.Collections.Generic;
using RimWorld;
using RimWorld.Planet;
using Verse;

namespace RimExodus
{
    /// <summary>
    /// 宿主地图上的无缝地块管理器。
    /// 负责生成/卸载无缝地块口袋地图，并维护接缝关系。
    ///
    /// 生成流程（参考 VMF GenerateVehicleMap，计划书 1.2）：
    /// 1. 用 WorldObjectMaker.MakeWorldObject 创建 MapParent_SeamlessTile。
    /// 2. 设置 sourceMap = 宿主地图。
    /// 3. 调用 MapGenerator.GenerateMap(..., isPocketMap: true)。
    /// 4. 加入 Find.World.pocketMaps。
    /// </summary>
    public class SeamlessTileManager : MapComponent
    {
        /// <summary>
        /// 接缝重叠带宽度（计划书 1.10 结论 4）。
        /// 对端地图与本地地图在接缝方向上的物理重叠宽度，需容纳传送点对。
        /// 用户确认边界应为 5 格。
        /// </summary>
        public const int DefaultOverlapBand = 5;

        /// <summary>是否已自动生成北侧地块（原型阶段：开档即生成北侧，便于测试）。</summary>
        private bool autoGeneratedNorth;

        /// <summary>延迟生成北侧地块的 tick 计数（MapGenerated 时 mapBeingGenerated 仍非空，需延迟到下一 tick）。</summary>
        private int pendingAutoGenerateTicks = -1;

        public SeamlessTileManager(Map map) : base(map)
        {
        }

        public override void MapComponentTick()
        {
            base.MapComponentTick();

            // 口袋地图上的 SeamlessTileManager 不参与自动生成（见 MapGenerated 注释）。
            if (map.IsPocketMap)
            {
                return;
            }

            // 延迟自动生成北侧地块：MapGenerated() 在 GenerateMap 内部调用，
            // 此时 MapGenerator.mapBeingGenerated 仍非空，GenerateTileMap 会拒绝。
            // 因此延迟到下一 tick 再生成。
            if (pendingAutoGenerateTicks > 0)
            {
                pendingAutoGenerateTicks--;
                if (pendingAutoGenerateTicks == 0)
                {
                    pendingAutoGenerateTicks = -1;
                    TryAutoGenerateNorth();
                }
            }
        }

        public override void MapGenerated()
        {
            base.MapGenerated();
            // 只在宿主地图（非口袋地图）上自动生成北侧地块。
            // 关键：SeamlessTileManager 是 MapComponent，会被 Map.FillComponents
            // 自动实例化到每一张地图上，包括 GenerateTileMap 生成的口袋地图本身。
            // 若不在口袋地图上跳过，口袋地图的 MapGenerated() 也会触发自动生成，
            // 导致"生成北侧 → 生成口袋地图 → 口袋地图又生成北侧"的无限递归卡死。
            if (map.IsPocketMap)
            {
                return;
            }
            // 开档自动生成北侧地块（原型阶段便于测试）。
            // 注意：此处 mapBeingGenerated 仍非空，不能直接生成，延迟到下一 tick。
            if (!autoGeneratedNorth)
            {
                autoGeneratedNorth = true;
                pendingAutoGenerateTicks = 1;
            }
        }

        /// <summary>
        /// 自动生成北侧地块（原型阶段：开档即生成北侧，便于测试渲染与接缝）。
        /// </summary>
        private void TryAutoGenerateNorth()
        {
            if (GetTileMapInDirection(0) != null)
            {
                return;
            }
            var mapSize = new IntVec3(map.Size.x, 1, map.Size.z);
            var overlapBand = DefaultOverlapBand;
            var parent = GenerateTileMap(0, mapSize, overlapBand);
            if (parent != null)
            {
                Log.Message($"[RimExodus] Auto-generated north seamless tile map (hostOffset={parent.hostOffset}).");
            }
        }

        /// <summary>
        /// 在宿主地图的指定方向生成一个无缝地块口袋地图。
        /// </summary>
        /// <param name="direction">六边形方向：0=北,1=东北,2=东南,3=南,4=西南,5=西北（原型四向兼容：1/2→东,4/5→西）</param>
        /// <param name="mapSize">口袋地图尺寸</param>
        /// <param name="overlapBand">接缝重叠带宽度（计划书 1.10 结论 4）</param>
        public MapParent_SeamlessTile GenerateTileMap(int direction, IntVec3 mapSize, int overlapBand)
        {
            if (MapGenerator.mapBeingGenerated != null)
            {
                Log.Warning("[RimExodus] Cannot generate seamless tile map during map generation.");
                return null;
            }

            var def = DefDatabase<WorldObjectDef>.GetNamedSilentFail("RimExodus_SeamlessTileMap");
            if (def == null)
            {
                Log.Error("[RimExodus] WorldObjectDef RimExodus_SeamlessTileMap not found.");
                return null;
            }

            var mapParent = (MapParent_SeamlessTile)WorldObjectMaker.MakeWorldObject(def);
            mapParent.mapGenerator = def.mapGenerator;
            mapParent.sourceMap = map;
            mapParent.Tile = 0;
            mapParent.direction = direction;

            // 计算 hostOffset：把口袋地图放在宿主地图边界之外，并留出重叠带
            mapParent.hostOffset = ComputeHostOffset(direction, mapSize, overlapBand);

            var interiorMap = MapGenerator.GenerateMap(mapSize, mapParent, mapParent.MapGeneratorDef,
                mapParent.ExtraGenStepDefs, isPocketMap: true);

            Find.World.pocketMaps.Add(mapParent);

            if (!Find.World.worldObjects.Contains(interiorMap.Parent))
            {
                Find.World.worldObjects.Add(interiorMap.Parent);
            }

            // 共享宿主地图的天空/天气
            interiorMap.skyManager = map.skyManager;
            interiorMap.weatherDecider = map.weatherDecider;
            interiorMap.weatherManager = map.weatherManager;

            // 自动在接缝重叠带放置一对传送点（本端 + 对端），两者宿主坐标重合。
            PlaceEnterSpots(mapParent, interiorMap, direction, overlapBand);

            return mapParent;
        }

        /// <summary>
        /// 在接缝重叠带放置一对传送点。
        /// 本端传送点挂在宿主地图上，对端传送点挂在口袋地图上，
        /// 两者在宿主坐标（drawPos）上重合于同一 tile，保证 Pawn 转移后视觉位置不跳变。
        /// </summary>
        private void PlaceEnterSpots(MapParent_SeamlessTile parent, Map interiorMap, int direction, int overlapBand)
        {
            var enterSpotDef = DefDatabase<ThingDef>.GetNamedSilentFail("RimExodus_SeamlessEnterSpot");
            if (enterSpotDef == null)
            {
                Log.Error("[RimExodus] ThingDef RimExodus_SeamlessEnterSpot not found.");
                return;
            }

            // 计算重叠带内的宿主坐标位置。
            // 传送点放在重叠带中央，避免紧贴地图边缘。
            var hostCell = ComputeEnterSpotHostCell(direction, overlapBand);
            Log.Message($"[RimExodus] PlaceEnterSpots dir={direction} hostCell={hostCell} hostSize={map.Size} hostOffset={parent.hostOffset}");
            if (!hostCell.InBounds(map))
            {
                Log.Warning($"[RimExodus] Enter spot host cell {hostCell} out of bounds.");
                return;
            }

            // 本端传送点：挂在宿主地图上，宿主→地块。
            var hostSpot = ThingMaker.MakeThing(enterSpotDef);
            var hostComp = hostSpot.TryGetComp<CompSeamlessTileEnterSpot>();
            if (hostComp != null)
            {
                hostComp.Configure(direction, newIsHostSide: true);
            }
            var spawnedHost = GenSpawn.Spawn(hostSpot, hostCell, map);
            Log.Message($"[RimExodus] Host enter spot spawned={spawnedHost != null} at {hostCell} walkable={hostCell.Walkable(map)}");

            // 对端传送点：挂在口袋地图上，地块→宿主。
            // 目标局部坐标 = 宿主坐标 - hostOffset，与宿主坐标重合。
            var localCell = SeamlessMapUtility.ToLocalCoord(hostCell, parent);
            Log.Message($"[RimExodus] Tile enter spot localCell={localCell} tileMapSize={interiorMap.Size}");
            if (!localCell.InBounds(interiorMap))
            {
                Log.Warning($"[RimExodus] Enter spot local cell {localCell} out of bounds on tile map.");
                return;
            }

            var tileSpot = ThingMaker.MakeThing(enterSpotDef);
            var tileComp = tileSpot.TryGetComp<CompSeamlessTileEnterSpot>();
            if (tileComp != null)
            {
                tileComp.Configure(direction, newIsHostSide: false);
            }
            var spawnedTile = GenSpawn.Spawn(tileSpot, localCell, interiorMap);
            Log.Message($"[RimExodus] Tile enter spot spawned={spawnedTile != null} at {localCell} walkable={localCell.Walkable(interiorMap)}");
        }

        /// <summary>
        /// 计算重叠带内传送点的宿主坐标。
        /// 传送点放在重叠带中央，避免紧贴地图边缘。
        /// </summary>
        private IntVec3 ComputeEnterSpotHostCell(int direction, int overlapBand)
        {
            var hostSize = map.Size;
            var mid = hostSize.x / 2;
            var bandMid = overlapBand / 2;

            switch (direction)
            {
                case 0: // 北
                    return new IntVec3(mid, 0, hostSize.z - bandMid);
                case 1: // 东北（原型暂作东）
                case 2: // 东南（原型暂作东）
                    return new IntVec3(hostSize.x - bandMid, 0, mid);
                case 3: // 南
                    return new IntVec3(mid, 0, bandMid);
                case 4: // 西南（原型暂作西）
                case 5: // 西北（原型暂作西）
                    return new IntVec3(bandMid, 0, mid);
                default:
                    return IntVec3.Zero;
            }
        }

        /// <summary>
        /// 计算口袋地图相对宿主地图的平移偏移。
        /// 口袋地图放在宿主地图边界之外，并在接缝方向留出重叠带。
        /// 六边形方向：0=北,1=东北,2=东南,3=南,4=西南,5=西北。
        /// 原型阶段四向兼容：1/2 暂时当作东，4/5 暂时当作西。
        /// </summary>
        private IntVec3 ComputeHostOffset(int direction, IntVec3 mapSize, int overlapBand)
        {
            var hostSize = map.Size;
            switch (direction)
            {
                case 0: // 北
                    return new IntVec3(0, 0, hostSize.z - overlapBand);
                case 1: // 东北（原型暂作东）
                case 2: // 东南（原型暂作东）
                    return new IntVec3(hostSize.x - overlapBand, 0, 0);
                case 3: // 南
                    return new IntVec3(0, 0, -mapSize.z + overlapBand);
                case 4: // 西南（原型暂作西）
                case 5: // 西北（原型暂作西）
                    return new IntVec3(-mapSize.x + overlapBand, 0, 0);
                default:
                    return IntVec3.Zero;
            }
        }

        /// <summary>
        /// 查询宿主地图指定方向上的无缝地块口袋地图。
        /// </summary>
        /// <param name="direction">六边形方向：0=北,1=东北,2=东南,3=南,4=西南,5=西北</param>
        public MapParent_SeamlessTile GetTileMapInDirection(int direction)
        {
            foreach (var pocketMap in Find.World.pocketMaps)
            {
                if (pocketMap is not MapParent_SeamlessTile parent)
                {
                    continue;
                }
                if (parent.sourceMap != map)
                {
                    continue;
                }
                if (parent.direction == direction)
                {
                    return parent;
                }
            }
            return null;
        }

        /// <summary>
        /// 卸载一个无缝地块口袋地图。
        /// </summary>
        public void RemoveTileMap(MapParent_SeamlessTile parent)
        {
            if (parent == null)
            {
                return;
            }

            var interiorMap = parent.Map;
            if (interiorMap != null)
            {
                parent.sourceMap = null;
                Find.World.pocketMaps.Remove(parent);
                Current.Game.DeinitAndRemoveMap(interiorMap, false);
            }
        }
    }
}
